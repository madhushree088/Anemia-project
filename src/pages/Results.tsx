import React, { useState, useEffect } from 'react';
import { Card } from '../components/ui/Card';
import { Button } from '../components/ui/Button';
import { Link } from 'react-router-dom';
import { 
  TrendingUp, 
  Calendar, 
  Heart, 
  Activity, 
  Download, 
  Share2,
  AlertTriangle,
  CheckCircle,
  Clock,
  Camera,
  FileText,
  Filter
} from 'lucide-react';
import { useAuth } from '../contexts/AuthContext';
import { db, isFirebaseEnabled } from '../lib/firebase';
import { getDocs, collection, query, where, orderBy } from 'firebase/firestore';
import { debugFirebase, addSampleData, clearTestData } from '../utils/debugUtils';
import { loadTestResultsWithFallback } from '../services/firestoreService';

interface TestResult {
  id: string;
  userId?: string | null;
  type: 'manual' | 'ai';
  status: 'normal' | 'mild' | 'moderate' | 'severe';
  hemoglobin: number;
  heartRate?: number;
  recommendations: string[];
  createdAt: string;
  assessmentData?: any;
  aiResults?: {
    fingernail: { status: string; confidence: number; type: string };
    eyelid: { status: string; confidence: number; type: string };
    overallConfidence: number;
  };
}

export const Results: React.FC = () => {
  const [results, setResults] = useState<TestResult[]>([]);
  const [selectedResult, setSelectedResult] = useState<TestResult | null>(null);
  const [filter, setFilter] = useState<'all' | 'manual' | 'ai'>('all');
  const { user } = useAuth();

  useEffect(() => {
    const loadResults = async () => {
      console.log('Loading results...');
      console.log('Firebase enabled:', isFirebaseEnabled);
      console.log('User ID:', user?.id);
      
      try {
        // Use the new Firestore service with fallback to localStorage
        const results = await loadTestResultsWithFallback(user?.id);
        
        console.log('Final results to display:', results.length, 'results');
        console.log('Results data:', results);
        
        setResults(results);
        if (results.length > 0) {
          setSelectedResult(results[0]);
        }
      } catch (error) {
        console.error('Error loading results:', error);
        // Fallback to localStorage only if there's an error
        const localResults: TestResult[] = JSON.parse(localStorage.getItem('testResults') || '[]');
        const userResults = user?.id 
          ? localResults.filter(result => result.userId === user.id)
          : localResults;
        
        userResults.sort((a, b) => new Date(b.createdAt).getTime() - new Date(a.createdAt).getTime());
        setResults(userResults);
        
        if (userResults.length > 0) {
          setSelectedResult(userResults[0]);
        }
      }
    };

    loadResults();
  }, [user?.id]);

  const getStatusColor = (status: string) => {
    switch (status) {
      case 'normal':
        return 'text-green-600 bg-green-50 border-green-200';
      case 'mild':
        return 'text-yellow-600 bg-yellow-50 border-yellow-200';
      case 'moderate':
        return 'text-orange-600 bg-orange-50 border-orange-200';
      case 'severe':
        return 'text-red-600 bg-red-50 border-red-200';
      default:
        return 'text-gray-600 bg-gray-50 border-gray-200';
    }
  };

  const getStatusIcon = (status: string) => {
    switch (status) {
      case 'normal':
        return <CheckCircle className="h-5 w-5" />;
      case 'mild':
      case 'moderate':
      case 'severe':
        return <AlertTriangle className="h-5 w-5" />;
      default:
        return <Activity className="h-5 w-5" />;
    }
  };

  const downloadResult = (result: TestResult) => {
    const content = `
ANEMIA TEST RESULT
==================

Patient: ${user?.name}
Date: ${new Date(result.createdAt).toLocaleDateString()}
Test Type: ${result.type === 'manual' ? 'Manual Assessment' : 'AI Analysis'}

RESULTS:
--------
Status: ${result.status.toUpperCase()}
Hemoglobin Level: ${result.hemoglobin.toFixed(1)} g/dL
${result.heartRate ? `Heart Rate: ${result.heartRate} bpm` : ''}

${result.type === 'ai' && result.aiResults ? `
AI ANALYSIS DETAILS:
-------------------
Fingernail Analysis: ${result.aiResults.fingernail.status} (${(result.aiResults.fingernail.confidence * 100).toFixed(1)}% confidence)
Eyelid Analysis: ${result.aiResults.eyelid.status} (${(result.aiResults.eyelid.confidence * 100).toFixed(1)}% confidence)
Overall Confidence: ${(result.aiResults.overallConfidence * 100).toFixed(1)}%
` : ''}

RECOMMENDATIONS:
---------------
${result.recommendations.map((rec, index) => `${index + 1}. ${rec}`).join('\n')}

DISCLAIMER:
----------
This test is for informational purposes only and should not replace professional medical advice. 
Please consult with a healthcare provider for proper diagnosis and treatment.

Generated by AnemiaCheck - ${new Date().toLocaleDateString()}
    `.trim();

    const blob = new Blob([content], { type: 'text/plain' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `anemia-test-result-${new Date(result.createdAt).toISOString().split('T')[0]}.txt`;
    document.body.appendChild(a);
    a.click();
    document.body.removeChild(a);
    URL.revokeObjectURL(url);
  };

  const shareResult = async (result: TestResult) => {
    const shareText = `My anemia test result: ${result.status.toUpperCase()} (Hemoglobin: ${result.hemoglobin.toFixed(1)} g/dL) - Tested with AnemiaCheck`;
    
    if (navigator.share) {
      try {
        await navigator.share({
          title: 'Anemia Test Result',
          text: shareText,
          url: window.location.origin
        });
      } catch (error) {
        console.log('Error sharing:', error);
        // Fallback to clipboard
        try {
          await navigator.clipboard.writeText(shareText);
          alert('Result copied to clipboard!');
        } catch (clipboardError) {
          console.log('Clipboard error:', clipboardError);
        }
      }
    } else {
      // Fallback: copy to clipboard
      try {
        await navigator.clipboard.writeText(shareText);
        alert('Result copied to clipboard!');
      } catch (error) {
        console.log('Clipboard error:', error);
        // Final fallback - show text in alert
        alert(`Share this result: ${shareText}`);
      }
    }
  };

  const filteredResults = results.filter(result => 
    filter === 'all' || result.type === filter
  );

  if (results.length === 0) {
    return (
      <div className="max-w-4xl mx-auto">
        {/* Debug Section - Remove in production */}
        <div className="mb-6 p-4 bg-gray-100 rounded-lg">
          <h3 className="font-semibold mb-2">Debug Tools (Development Only)</h3>
          <div className="flex space-x-2 text-sm">
            <Button size="sm" onClick={() => { debugFirebase(); }} variant="outline">
              Check Firebase
            </Button>
            <Button size="sm" onClick={() => { addSampleData(); window.location.reload(); }} variant="outline">
              Add Sample Data
            </Button>
            <Button size="sm" onClick={() => { clearTestData(); window.location.reload(); }} variant="outline">
              Clear Data
            </Button>
          </div>
        </div>
        
        <div className="text-center py-12">
          <TrendingUp className="h-16 w-16 text-gray-400 mx-auto mb-4" />
          <h1 className="text-2xl font-bold text-gray-900 mb-2">No Test Results Yet</h1>
          <p className="text-gray-600 mb-6">
            Complete a manual assessment or AI test to see your results here.
          </p>
          <div className="flex flex-col sm:flex-row gap-4 justify-center">
            <Link to="/assessment">
              <Button className="w-full sm:w-auto">
                Take Manual Assessment
              </Button>
            </Link>
            <Link to="/ai-test">
              <Button variant="outline" className="w-full sm:w-auto">
                Try AI Test
              </Button>
            </Link>
          </div>
        </div>
      </div>
    );
  }

  return (
    <div className="max-w-7xl mx-auto">
      <div className="mb-8">
        <div className="flex items-center justify-between">
          <div>
            <div className="flex items-center space-x-3 mb-2">
              <TrendingUp className="h-8 w-8 text-blue-600" />
              <h1 className="text-3xl font-bold text-gray-900">Test Results</h1>
            </div>
            <p className="text-gray-600">
              View and manage your anemia test results and health recommendations.
            </p>
          </div>
          
          <div className="flex items-center space-x-2">
            <Filter className="h-4 w-4 text-gray-500" />
            <select
              value={filter}
              onChange={(e) => setFilter(e.target.value as 'all' | 'manual' | 'ai')}
              className="border border-gray-300 rounded-lg px-3 py-1 text-sm"
            >
              <option value="all">All Tests</option>
              <option value="manual">Manual Assessment</option>
              <option value="ai">AI Tests</option>
            </select>
          </div>
        </div>
      </div>

      <div className="grid grid-cols-1 lg:grid-cols-3 gap-8">
        {/* Results List */}
        <div className="lg:col-span-1">
          <Card>
            <h2 className="text-lg font-semibold text-gray-900 mb-4">Test History</h2>
            <div className="space-y-3">
              {filteredResults.map((result) => (
                <div
                  key={result.id}
                  onClick={() => setSelectedResult(result)}
                  className={`p-3 rounded-lg border cursor-pointer transition-colors ${
                    selectedResult?.id === result.id
                      ? 'border-blue-300 bg-blue-50'
                      : 'border-gray-200 hover:border-gray-300'
                  }`}
                >
                  <div className="flex items-center justify-between mb-2">
                    <div className="flex items-center space-x-2">
                      {result.type === 'manual' ? (
                        <FileText className="h-4 w-4 text-blue-600" />
                      ) : (
                        <Camera className="h-4 w-4 text-purple-600" />
                      )}
                      <span className="text-sm font-medium text-gray-900">
                        {result.type === 'manual' ? 'Manual Assessment' : 'AI Test'}
                      </span>
                    </div>
                    <span className={`inline-flex items-center px-2 py-1 rounded-full text-xs font-medium border ${getStatusColor(result.status)}`}>
                      {getStatusIcon(result.status)}
                      <span className="ml-1">{result.status}</span>
                    </span>
                  </div>
                  <div className="flex items-center justify-between text-sm text-gray-600">
                    <span>{result.hemoglobin.toFixed(1)} g/dL</span>
                    <div className="flex items-center space-x-1">
                      <Calendar className="h-3 w-3" />
                      <span>{new Date(result.createdAt).toLocaleDateString()}</span>
                    </div>
                  </div>
                </div>
              ))}
            </div>
          </Card>
        </div>

        {/* Detailed Result View */}
        <div className="lg:col-span-2">
          {selectedResult && (
            <div className="space-y-6">
              {/* Result Summary */}
              <Card>
                <div className="flex items-center justify-between mb-6">
                  <div className="flex items-center space-x-3">
                    {selectedResult.type === 'manual' ? (
                      <FileText className="h-6 w-6 text-blue-600" />
                    ) : (
                      <Camera className="h-6 w-6 text-purple-600" />
                    )}
                    <div>
                      <h2 className="text-xl font-semibold text-gray-900">
                        {selectedResult.type === 'manual' ? 'Manual Assessment' : 'AI Test'} Result
                      </h2>
                      <div className="flex items-center space-x-2 text-sm text-gray-600">
                        <Clock className="h-4 w-4" />
                        <span>{new Date(selectedResult.createdAt).toLocaleString()}</span>
                      </div>
                    </div>
                  </div>
                  
                  <div className="flex space-x-2">
                    <Button
                      variant="outline"
                      size="sm"
                      onClick={() => downloadResult(selectedResult)}
                      className="flex items-center space-x-1"
                    >
                      <Download className="h-4 w-4" />
                      <span>Download</span>
                    </Button>
                    <Button
                      variant="outline"
                      size="sm"
                      onClick={() => shareResult(selectedResult)}
                      className="flex items-center space-x-1"
                    >
                      <Share2 className="h-4 w-4" />
                      <span>Share</span>
                    </Button>
                  </div>
                </div>

                {/* Health Metrics */}
                <div className="grid grid-cols-1 md:grid-cols-3 gap-6 mb-6">
                  <div className="text-center">
                    <div className={`inline-flex items-center justify-center w-12 h-12 rounded-full border-2 ${getStatusColor(selectedResult.status)} mb-2`}>
                      {getStatusIcon(selectedResult.status)}
                    </div>
                    <div className="text-2xl font-bold text-gray-900">{selectedResult.status}</div>
                    <div className="text-sm text-gray-600">Anemia Status</div>
                  </div>
                  
                  <div className="text-center">
                    <div className="inline-flex items-center justify-center w-12 h-12 rounded-full bg-red-50 border-2 border-red-200 mb-2">
                      <Heart className="h-6 w-6 text-red-600" />
                    </div>
                    <div className="text-2xl font-bold text-gray-900">{selectedResult.hemoglobin.toFixed(1)}</div>
                    <div className="text-sm text-gray-600">Hemoglobin (g/dL)</div>
                  </div>
                  
                  {selectedResult.heartRate && (
                    <div className="text-center">
                      <div className="inline-flex items-center justify-center w-12 h-12 rounded-full bg-blue-50 border-2 border-blue-200 mb-2">
                        <Activity className="h-6 w-6 text-blue-600" />
                      </div>
                      <div className="text-2xl font-bold text-gray-900">{selectedResult.heartRate}</div>
                      <div className="text-sm text-gray-600">Heart Rate (bpm)</div>
                    </div>
                  )}
                </div>

                {/* AI Analysis Details */}
                {selectedResult.type === 'ai' && selectedResult.aiResults && (
                  <div className="border-t border-gray-200 pt-6">
                    <h3 className="text-lg font-semibold text-gray-900 mb-4">AI Analysis Details</h3>
                    <div className="grid grid-cols-1 md:grid-cols-2 gap-4">
                      <div className="bg-gray-50 rounded-lg p-4">
                        <div className="flex items-center space-x-2 mb-2">
                          <Camera className="h-4 w-4 text-gray-600" />
                          <span className="font-medium text-gray-900">Fingernail Analysis</span>
                        </div>
                        <div className="text-sm text-gray-600">
                          <div>Status: <span className="font-medium">{selectedResult.aiResults.fingernail.status}</span></div>
                          <div>Confidence: <span className="font-medium">{(selectedResult.aiResults.fingernail.confidence * 100).toFixed(1)}%</span></div>
                        </div>
                      </div>
                      
                      <div className="bg-gray-50 rounded-lg p-4">
                        <div className="flex items-center space-x-2 mb-2">
                          <Camera className="h-4 w-4 text-gray-600" />
                          <span className="font-medium text-gray-900">Eyelid Analysis</span>
                        </div>
                        <div className="text-sm text-gray-600">
                          <div>Status: <span className="font-medium">{selectedResult.aiResults.eyelid.status}</span></div>
                          <div>Confidence: <span className="font-medium">{(selectedResult.aiResults.eyelid.confidence * 100).toFixed(1)}%</span></div>
                        </div>
                      </div>
                    </div>
                    <div className="mt-4 text-center">
                      <span className="text-sm text-gray-600">
                        Overall AI Confidence: <span className="font-medium">{(selectedResult.aiResults.overallConfidence * 100).toFixed(1)}%</span>
                      </span>
                    </div>
                  </div>
                )}
              </Card>

              {/* Recommendations */}
              <Card>
                <h3 className="text-lg font-semibold text-gray-900 mb-4">Health Recommendations</h3>
                <div className="space-y-3">
                  {selectedResult.recommendations.map((recommendation, index) => (
                    <div key={index} className="flex items-start space-x-3">
                      <div className="flex-shrink-0 w-6 h-6 bg-blue-100 rounded-full flex items-center justify-center mt-0.5">
                        <span className="text-xs font-medium text-blue-600">{index + 1}</span>
                      </div>
                      <p className="text-gray-700">{recommendation}</p>
                    </div>
                  ))}
                </div>
                
                <div className="mt-6 p-4 bg-yellow-50 border border-yellow-200 rounded-lg">
                  <div className="flex items-start space-x-2">
                    <AlertTriangle className="h-5 w-5 text-yellow-600 mt-0.5" />
                    <div>
                      <h4 className="font-medium text-yellow-800">Important Disclaimer</h4>
                      <p className="text-sm text-yellow-700 mt-1">
                        This test is for informational purposes only and should not replace professional medical advice. 
                        Please consult with a healthcare provider for proper diagnosis and treatment.
                      </p>
                    </div>
                  </div>
                </div>
              </Card>
            </div>
          )}
        </div>
      </div>
    </div>
  );
};